// TestPrettyJSONMatchesPython compares the Python-compatible encoder against
// json.dumps(..., ensure_ascii=False, indent=2, sort_keys=True) output.
func TestPrettyJSONMatchesPython(t *testing.T) {
	cases := decodeFixture[map[string]struct {
		Value    any    `json:"value"`
		Expected string `json:"expected"`
	}](t, "testdata/json_cases.json")
	if len(cases) == 0 {
		t.Fatal("json fixtures are empty")
	}
	for name, testCase := range cases {
		t.Run(name, func(t *testing.T) {
			if got := prettyJSON(testCase.Value); got != testCase.Expected {
				t.Errorf("prettyJSON mismatch\n--- want ---\n%s\n--- got ---\n%s", testCase.Expected, got)
			}
		})
	}
}

// TestDescribeTools mirrors ToolRegistry.describe.
func TestDescribeTools(t *testing.T) {
	registry := tools.BuildDefaultRegistry()
	described := DescribeTools(registry)
	if len(described) != len(registry.Names()) {
		t.Fatalf("described %d tools, registry has %d", len(described), len(registry.Names()))
	}
	for index, entry := range described {
		if domain.StringFrom(entry["name"]) != registry.Names()[index] {
			t.Fatalf("describe order mismatch at %d: %v vs %s", index, entry["name"], registry.Names()[index])
		}
		if _, ok := entry["description"]; !ok {
			t.Fatalf("described tool %v has no description", entry["name"])
		}
	}
	if len(DescribeTools(nil)) != 0 {
		t.Fatal("DescribeTools(nil) should be empty")
	}
}
